import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

export const PROJECT_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIST_FILES = ['index.html', 'style.css', 'faq.js', 'app.js', 'assets/anc-symbol.svg', 'assets/ha7ch-black.svg'];
const sha256 = data => createHash('sha256').update(data).digest('hex');
const cspHash = text => `'sha256-${createHash('sha256').update(text, 'utf8').digest('base64')}'`;

function replaceOnce(text, search, replacement) {
  if (text.split(search).length !== 2) throw new Error(`Expected exactly one source marker: ${search}`);
  return text.replace(search, () => replacement);
}

export async function buildArtifacts(projectRoot = PROJECT_ROOT) {
  const sources = {};
  const sourceHashes = {};
  for (const name of DIST_FILES) {
    const bytes = await readFile(path.join(projectRoot, 'dist', name));
    sources[name] = bytes.toString('utf8');
    sourceHashes[`dist/${name}`] = sha256(bytes);
  }
  let html = sources['index.html'];
  if (/<(?:script|style)\b/i.test(html.replace(/<script src="(?:faq|app)\.js" defer><\/script>/g, ''))) {
    throw new Error('Unexpected inline script/style in source HTML; review the CSP build contract.');
  }
  if (/\son\w+\s*=|\sstyle\s*=/i.test(html)) throw new Error('Inline handlers/style attributes are not supported.');
  if (/@import\b|url\s*\(/i.test(sources['style.css'])) throw new Error('External CSS resources require an explicit CSP review.');
  if (/<\/style/i.test(sources['style.css'])) throw new Error('Unexpected closing style tag in CSS.');
  html = replaceOnce(html, '<link rel="stylesheet" href="style.css">', `<style>${sources['style.css']}</style>`);
  for (const filename of ['faq.js', 'app.js']) {
    html = replaceOnce(html, `  <script src="${filename}" defer></script>\n`, '');
  }
  for (const asset of ['anc-symbol.svg', 'ha7ch-black.svg']) {
    const data = Buffer.from(sources[`assets/${asset}`], 'utf8').toString('base64');
    html = replaceOnce(html, `"assets/${asset}"`, `"data:image/svg+xml;base64,${data}"`);
  }
  const scripts = ['faq.js', 'app.js'].map(name => sources[name].replace(/<\/script/gi, '<\\/script'));
  html = replaceOnce(html, '</body>', `${scripts.map(js => `<script>${js}</script>`).join('\n')}\n</body>`);
  if (/(?:src|href)="(?:app\.js|faq\.js|style\.css|assets\/)/.test(html)) throw new Error('Unbundled local asset reference.');
  const htmlHash = sha256(Buffer.from(html, 'utf8'));
  const csp = [
    "default-src 'none'",
    `script-src ${scripts.map(cspHash).join(' ')}`,
    `style-src ${cspHash(sources['style.css'])}`,
    'img-src data:',
    "base-uri 'none'",
    "object-src 'none'",
    "form-action 'none'",
    "frame-ancestors 'none'"
  ].join('; ');
  const handlerSource = await readFile(path.join(projectRoot, 'integration', 'homepage-handler.mjs'), 'utf8');
  sourceHashes['integration/homepage-handler.mjs'] = sha256(handlerSource);
  sourceHashes['scripts/build.mjs'] = sha256(await readFile(path.join(projectRoot, 'scripts', 'build.mjs')));
  const module = [
    '// Generated by scripts/build.mjs. Imported by the main-site product route.',
    '// Also contains an optional legacy Worker route helper, not a Worker entrypoint.',
    `export const ANC_HOMEPAGE_SHA256 = ${JSON.stringify(htmlHash)};`,
    `export const ANC_HOMEPAGE_CSP = ${JSON.stringify(csp)};`,
    `export const ANC_HOMEPAGE_HTML = ${JSON.stringify(html)};`,
    handlerSource,
    ''
  ].join('\n');
  const outputs = {
    'release/anc-standalone.html': html,
    'release/anc-homepage.mjs': module
  };
  const manifest = {
    format: 1,
    homepage_sha256: htmlHash,
    homepage_bytes: Buffer.byteLength(html),
    site_version_header: 'X-ANC-Site-Version',
    production_url: 'https://ha7ch.com/ai-native-company',
    allowed_production_hosts: ['ha7ch.com'],
    legacy_worker_allowed_hosts: ['anc.ha7ch.com'],
    source_sha256: sourceHashes,
    output_sha256: Object.fromEntries(Object.entries(outputs).map(([name, content]) => [name, sha256(content)])),
    content_security_policy: csp
  };
  outputs['release/manifest.json'] = JSON.stringify(manifest, null, 2) + '\n';
  return outputs;
}

export async function verifyArtifacts(projectRoot, artifacts) {
  const stale = [];
  for (const [name, content] of Object.entries(artifacts)) {
    try {
      if (!Buffer.from(content).equals(await readFile(path.join(projectRoot, name)))) stale.push(name);
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
      stale.push(name);
    }
  }
  if (stale.length) throw new Error(`Missing/stale release files: ${stale.join(', ')}. Run npm run build.`);
}

async function main() {
  const args = process.argv.slice(2);
  if (args.some(arg => arg !== '--check') || args.length > 1) throw new Error('Usage: node scripts/build.mjs [--check]');
  const artifacts = await buildArtifacts();
  if (args.includes('--check')) {
    await verifyArtifacts(PROJECT_ROOT, artifacts);
    console.log('Release artifacts match the sources.');
  } else {
    await mkdir(path.join(PROJECT_ROOT, 'release'), { recursive: true });
    for (const [name, content] of Object.entries(artifacts)) await writeFile(path.join(PROJECT_ROOT, name), content);
    const manifest = JSON.parse(artifacts['release/manifest.json']);
    console.log(`Built ${manifest.homepage_bytes} byte homepage. SHA256 ${manifest.homepage_sha256}`);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  main().catch(error => { console.error(error.message); process.exitCode = 1; });
}
